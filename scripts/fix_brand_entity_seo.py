#!/usr/bin/env python3
"""Tighten the brand-entity signals Google uses to recognise "Zeno Hosp".

Google currently rewrites the query "zeno hosp" to "zeno hospital", which means
it has not learned that Zeno Hosp is a brand. Three site-wide inconsistencies
feed that:

1. Every page carries two conflicting Open Graph blocks (an old generic one and
   a later injected page-specific one). Duplicate og:title/og:description let
   Google and social crawlers pick arbitrarily, so the brand string it sees is
   unstable.
2. og:site_name is "Zenohosp" while the Organization schema says "ZenoHosp" —
   two spellings of the same entity.
3. Only an SVG favicon is declared, so the SERP falls back to a generic globe
   instead of the brand mark.

This script collapses the OG tags into one block (later values win, since those
are the page-specific ones), normalises the brand string, syncs the Twitter
card to match, and declares the raster favicons.
"""

import pathlib
import re
import sys

BRAND = "ZenoHosp"

SKIP_DIRS = {".git", "node_modules", "scripts", "components"}

OG_ORDER = ["og:type", "og:site_name", "og:url", "og:title", "og:description", "og:image"]

def _meta_pattern(ns):
    """Match a meta tag in either attribute order.

    Pages generated by the older scripts emit content-then-property; the newer
    injected blocks emit property-then-content. Both must be collapsed or the
    duplicates survive.
    """
    return re.compile(
        r'[ \t]*<meta\s+(?:'
        rf'property="({ns}:[a-z_]+)"\s*\n?\s*content="([^"]*)"'
        r'|'
        rf'content="([^"]*)"\s*\n?\s*property="({ns}:[a-z_]+)"'
        # Trailing newline is optional: some generated pages pack several meta
        # tags onto a single line, and those duplicates must be caught too.
        r')\s*/?>[ \t]*\n?',
        re.IGNORECASE,
    )


OG_TAG = _meta_pattern("og")
TWITTER_TAG = _meta_pattern("twitter")


def tag_parts(m):
    """Return (property, content) regardless of which attribute order matched."""
    if m.group(1):
        return m.group(1).lower(), m.group(2)
    return m.group(4).lower(), m.group(3)
FAVICON_TAG = re.compile(
    r'[ \t]*<link[^>]*rel="(?:icon|shortcut icon|apple-touch-icon)"[^>]*>\s*\n',
    re.IGNORECASE,
)

FAVICONS = """  <!-- Favicon - raster sizes so Google can index the brand mark -->
  <link rel="icon" href="/favicon.ico" sizes="any">
  <link rel="icon" type="image/svg+xml" href="/images/favicon.svg">
  <link rel="icon" type="image/png" sizes="48x48" href="/images/favicon-48.png">
  <link rel="icon" type="image/png" sizes="192x192" href="/images/favicon-192.png">
  <link rel="apple-touch-icon" href="/images/apple-touch-icon.png">
"""


def collapse(html, pattern, order, overrides):
    """Merge every matching meta tag into one block at the first tag's position."""
    matches = list(pattern.finditer(html))
    if not matches:
        return html, False

    values = {}
    for m in matches:
        prop, content = tag_parts(m)
        values[prop] = content  # later duplicates win
    values.update(overrides)

    block = "".join(
        f'  <meta property="{p}" content="{values[p]}">\n'
        for p in order
        if values.get(p)
    )
    extra = sorted(k for k in values if k not in order)
    block += "".join(f'  <meta property="{k}" content="{values[k]}">\n' for k in extra)

    # Mark where the first tag sat, drop every occurrence, then drop the merged
    # block onto the marker. Avoids index arithmetic against a shifting string.
    sentinel = "\x00MERGED\x00"
    seen = {"n": 0}

    def mark(_m):
        seen["n"] += 1
        return sentinel if seen["n"] == 1 else ""

    out = pattern.sub(mark, html).replace(sentinel, block)
    return out, out != html


def normalise_brand_casing(html):
    """Spell the brand "ZenoHosp" in description/keywords meta.

    Deliberately scoped to those two tags: the schema alternateName lists
    "Zenohosp" on purpose (it enumerates spelling variants for Google), and
    lowercase "zenohosp" inside URLs must not be touched.
    """

    def fix(m):
        return m.group(0).replace("Zenohosp", BRAND)

    return re.sub(
        r'<meta\s+name="(?:description|keywords)"\s*\n?\s*content="[^"]*"\s*/?>',
        fix,
        html,
        flags=re.IGNORECASE,
    )


def process(path):
    html = path.read_text(encoding="utf-8")
    original = html

    html = normalise_brand_casing(html)
    og_values = dict(tag_parts(m) for m in OG_TAG.finditer(html))

    og_overrides = {"og:site_name": BRAND}
    for key in ("og:title", "og:description"):
        if "Zenohosp" in og_values.get(key, ""):
            og_overrides[key] = og_values[key].replace("Zenohosp", BRAND)
            og_values[key] = og_overrides[key]
    html, _ = collapse(html, OG_TAG, OG_ORDER, og_overrides)

    # A Twitter card that disagrees with the OG block is another wobbly signal.
    tw_overrides = {}
    if og_values.get("og:title"):
        tw_overrides["twitter:title"] = og_values["og:title"]
    if og_values.get("og:description"):
        tw_overrides["twitter:description"] = og_values["og:description"]
    html, _ = collapse(
        html,
        TWITTER_TAG,
        ["twitter:card", "twitter:url", "twitter:title", "twitter:description", "twitter:image"],
        tw_overrides,
    )

    if "/images/favicon-48.png" not in html:
        icons = list(FAVICON_TAG.finditer(html))
        if icons:
            html = html[: icons[0].start()] + FAVICONS + FAVICON_TAG.sub("", html[icons[0].start():])
        else:
            # A handful of doc pages declare no icon at all; seed the block
            # right after <head> so they inherit the brand mark too.
            head = re.search(r"<head[^>]*>[ \t]*\n?", html, re.IGNORECASE)
            if head:
                html = html[: head.end()] + FAVICONS + html[head.end():]

    if html != original:
        path.write_text(html, encoding="utf-8")
        return True
    return False


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    changed = 0
    for path in sorted(root.rglob("*.html")):
        if SKIP_DIRS & set(path.relative_to(root).parts):
            continue
        if process(path):
            changed += 1
    print(f"updated {changed} pages")


if __name__ == "__main__":
    sys.exit(main())
